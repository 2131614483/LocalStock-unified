const { _electron } = require('playwright')
const fs = require('fs')
const os = require('os')
const path = require('path')

const executablePath = path.resolve(process.env.LOCALSTOCK_TEST_EXE || 'dist/win-unpacked/LocalStock.exe')
const shot = path.resolve(__dirname, '../test-results/23-multi-period-predict.png')
const assert = (condition, message) => { if (!condition) throw new Error(message) }

async function main() {
  const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'localstock-multi-predict-'))
  let app
  try {
    app = await _electron.launch({
      executablePath,
      args: [`--user-data-dir=${profile}`],
      env: { ...process.env, APPDATA: profile, LOCALSTOCK_NO_SINGLETON: '1' }
    })
    const win = await app.firstWindow()
    await win.waitForLoadState('domcontentloaded')
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0]?.show())
    await win.waitForTimeout(5000)
    await win.getByRole('button', { name: '自选股', exact: true }).click()
    await win.locator('.stock-table tbody tr').first().click()
    await win.waitForTimeout(3500)
    await win.locator('.tab').filter({ hasText: /^日K$/ }).click()
    await win.getByText('AI 多周期预测', { exact: true }).waitFor({ timeout: 20_000 })
    const chartMain = win.locator('.minute-layout .splitpane > .splitpane-main')
    const predictPanel = win.locator('.multi-predict')
    await win.getByRole('button', { name: '浮动AI多周期预测窗口' }).click()
    await win.waitForTimeout(200)
    const floatBefore = await predictPanel.boundingBox()
    assert(floatBefore, 'AI多周期预测窗口没有进入浮动状态')
    const floatHeader = predictPanel.locator('.minute-predict-head')
    const headerBox = await floatHeader.boundingBox()
    assert(headerBox, '找不到浮动窗口拖动标题栏')
    await win.mouse.move(headerBox.x + 80, headerBox.y + 12)
    await win.mouse.down()
    await win.mouse.move(headerBox.x + 10, headerBox.y + 70, { steps: 5 })
    await win.mouse.up()
    const floatAfter = await predictPanel.boundingBox()
    assert(floatAfter && (Math.abs(floatAfter.x - floatBefore.x) > 20 || Math.abs(floatAfter.y - floatBefore.y) > 20), '浮动窗口无法自由拖拽')
    assert((await chartMain.boundingBox())?.width > 900, '浮动后K线区域没有自动铺满')
    await win.getByRole('button', { name: '停靠AI多周期预测窗口' }).click()
    await win.getByRole('button', { name: '展开AI多周期预测窗口' }).click()
    await win.waitForTimeout(200)
    assert((await chartMain.boundingBox())?.width === 0, '展开后图表区域没有收起')
    assert((await predictPanel.boundingBox())?.width > 700, 'AI多周期预测窗口没有展开')
    await win.getByRole('button', { name: '还原AI多周期预测窗口' }).click()
    await win.getByRole('button', { name: '最小化AI多周期预测窗口' }).click()
    await win.waitForTimeout(200)
    assert((await predictPanel.boundingBox())?.width <= 240, 'AI多周期预测窗口没有最小化')
    assert(await win.locator('.multi-period-checks').count() === 0, '最小化后仍显示面板内容')
    await win.getByRole('button', { name: '恢复AI多周期预测窗口' }).click()
    const checks = win.locator('.multi-period-check input')
    assert(await checks.count() === 12, '没有显示全部 12 个分析周期')
    assert(await win.locator('.multi-period-check.current').getByText('日K', { exact: true }).count() === 1, '当前周期未高亮')
    await win.getByRole('button', { name: /分析工具代码/ }).click()
    const editor = win.locator('.multi-predict-editor')
    await editor.waitFor()
    assert((await editor.inputValue()).includes('AI预测·趋势目标'), '默认预测代码未加载')
    const codeEditable = await editor.isEditable()
    const scrollable = await editor.evaluate((el) => {
      const style = getComputedStyle(el)
      return ['scroll', 'auto'].includes(style.overflowY) && ['scroll', 'auto'].includes(style.overflowX)
    })
    assert(scrollable, '分析工具代码没有横向/纵向滚动能力')
    const originalCode = await editor.inputValue()
    await editor.fill(`${originalCode}\n# 历史验证`)
    await editor.blur()
    await win.waitForTimeout(900)
    await win.locator('.multi-code-actions').getByRole('button', { name: /历史/ }).click()
    assert(await win.locator('.multi-code-history button').count() >= 1, '分析工具代码没有保存历史版本')
    await win.locator('.multi-code-actions').getByRole('button', { name: /恢复默认/ }).click()
    assert((await editor.inputValue()).includes('AI预测·趋势目标'), '分析工具代码复位失败')
    assert(await win.getByPlaceholder('告诉 AI 如何生成或调优分析代码…').count() === 1, '分析工具代码未接入 AI')
    await win.getByRole('button', { name: /分析工具代码/ }).click()
    const labels = win.locator('.multi-period-check')
    for (let i = 0; i < await labels.count(); i += 1) {
      const label = labels.nth(i)
      const input = label.locator('input')
      const text = (await label.innerText()).trim()
      if (text !== '日K' && await input.isChecked()) await label.click()
      if (text === '日K' && !(await input.isChecked())) await label.click()
    }
    await win.getByRole('button', { name: /统一分析 1 个周期/ }).click()
    await win.locator('.mp-annot').waitFor({ timeout: 30_000 })
    assert((await win.locator('.mp-annot').innerText()).includes('3 条线'), '日K预测代码没有生成三条画线')
    assert(!((await win.locator('.mp-annotations').innerText()).includes('Cannot read properties')), '仍然出现空数据指针错误')
    await win.screenshot({ path: shot, fullPage: false })
    console.log(JSON.stringify({ ok: true, periods: await checks.count(), codeEditable, scrollable, analyzed: await win.locator('.mp-annot').innerText(), screenshot: shot }, null, 2))
  } finally {
    if (app) await app.close().catch(() => {})
    fs.rmSync(profile, { recursive: true, force: true })
  }
}

main().catch((error) => { console.error(error); process.exit(1) })
